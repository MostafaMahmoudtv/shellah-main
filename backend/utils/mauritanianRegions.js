// دوال مساعدة
export const getAllWilayas = () => Object.keys(mauritanianRegions);

export const getdairasByWilaya = (wilaya) => {
  return mauritanianRegions[wilaya] ? Object.keys(mauritanianRegions[wilaya]) : [];
};

export const getBaladiasBydaira = (wilaya, daira) => {
  return mauritanianRegions[wilaya]?.[daira] || [];
};

export const validateWilaya = (wilaya) => {
  return mauritanianRegions[wilaya] !== undefined;
};

export const validateMoughataa = (wilaya, moughataa) => {
  return mauritanianRegions[wilaya] && mauritanianRegions[wilaya][moughataa] !== undefined;
};

// البحث في العربية أو الفرنسية
export const searchWilaya = (searchTerm) => {
  const allWilayas = getAllWilayas();
  return allWilayas.filter(wilaya => 
    wilaya.toLowerCase().includes(searchTerm.toLowerCase())
  );
};