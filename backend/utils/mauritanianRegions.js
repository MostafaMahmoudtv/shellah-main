// ==================== الدوال المساعدة ====================

// جلب كل الولايات (من اللغتين معاً)
export const getAllWilayas = () => {
  const arabicWilayas = Object.keys(mauritanianRegions.ar);
  const frenchWilayas = Object.keys(mauritanianRegions.fr);
  return [...arabicWilayas, ...frenchWilayas];
};

// جلب الولايات بالعربية فقط
export const getArabicWilayas = () => {
  return Object.keys(mauritanianRegions.ar);
};

// جلب الولايات بالفرنسية فقط
export const getFrenchWilayas = () => {
  return Object.keys(mauritanianRegions.fr);
};

// جلب المقاطعات حسب الولاية (يدعم العربي والفرنسي)
export const getMoughataasByWilaya = (wilaya) => {
  // البحث في العربية
  if (mauritanianRegions.ar[wilaya]) {
    return Object.keys(mauritanianRegions.ar[wilaya]);
  }
  // البحث في الفرنسية
  if (mauritanianRegions.fr[wilaya]) {
    return Object.keys(mauritanianRegions.fr[wilaya]);
  }
  return [];
};

// جلب البلديات حسب المقاطعة (يدعم العربي والفرنسي)
export const getBaladiasByMoughataa = (wilaya, moughataa) => {
  // البحث في العربية
  if (mauritanianRegions.ar[wilaya] && mauritanianRegions.ar[wilaya][moughataa]) {
    return mauritanianRegions.ar[wilaya][moughataa];
  }
  // البحث في الفرنسية
  if (mauritanianRegions.fr[wilaya] && mauritanianRegions.fr[wilaya][moughataa]) {
    return mauritanianRegions.fr[wilaya][moughataa];
  }
  return [];
};

// التحقق من صحة الولاية (يدعم العربي والفرنسي)
export const validateWilaya = (wilaya) => {
  return mauritanianRegions.ar[wilaya] !== undefined || mauritanianRegions.fr[wilaya] !== undefined;
};

// التحقق من صحة المقاطعة (يدعم العربي والفرنسي)
export const validateMoughataa = (wilaya, moughataa) => {
  return (mauritanianRegions.ar[wilaya] && mauritanianRegions.ar[wilaya][moughataa]) ||
         (mauritanianRegions.fr[wilaya] && mauritanianRegions.fr[wilaya][moughataa]);
};

// البحث في الولايات (يدعم العربي والفرنسي)
export const searchWilaya = (searchTerm) => {
  const allWilayas = getAllWilayas();
  return allWilayas.filter(wilaya => 
    wilaya.toLowerCase().includes(searchTerm.toLowerCase())
  );
};

// جلب اللغة التي تنتمي لها الولاية
export const getWilayaLanguage = (wilaya) => {
  if (mauritanianRegions.ar[wilaya]) return 'ar';
  if (mauritanianRegions.fr[wilaya]) return 'fr';
  return null;
};